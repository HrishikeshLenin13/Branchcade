// Turns evidence/control-crawl.json into docs/production/CONTROL_INVENTORY.md (every control)
// and prints summary counts for CONTROL_ACCEPTANCE_MATRIX.md.
import { readFileSync, writeFileSync } from 'node:fs'
const [input, output] = process.argv.slice(2)
const report = JSON.parse(readFileSync(input, 'utf8'))
const esc = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ')
const classify = (c) =>
  c.action === 'disabled'
    ? c.effect[0] === 'no reason given'
      ? 'DISABLED, NO REASON'
      : 'DISABLED WITH REASON'
    : c.action.startsWith('file input')
      ? 'COVERED BY IMPORT JOURNEY'
      : c.action.includes('FAILED') || c.action === 'not present after reload'
        ? 'NOT ACTIVATED'
        : c.errors.length
          ? 'ERROR'
          : c.effect.length
            ? 'PASS'
            : 'NO OBSERVABLE EFFECT'
const lines = [
  '# Control inventory (generated)',
  '',
  `Generated by \`scripts/final-control-report.mjs\` from \`evidence/control-crawl.json\` (${report.browser}, 1366×768). Each row was activated in its own fresh synthetic browser after reloading its route state, with collapsed sections expanded. Native confirm prompts were accepted.`,
  '',
]
const totals = {}
for (const s of report.states) {
  lines.push(
    `## ${s.state}`,
    '',
    '| # | Control | Action | Observed effect | Result |',
    '| - | ------- | ------ | --------------- | ------ |',
  )
  for (const c of s.controls) {
    const r = classify(c)
    totals[r] = (totals[r] ?? 0) + 1
    lines.push(
      `| ${c.index} | ${esc(c.tag)} “${esc(c.label || '(unnamed)')}” | ${esc(c.action)} | ${esc(c.effect.join('; ') || '—')}${c.errors.length ? ' · errors: ' + esc(c.errors.join(' / ')) : ''} | ${r} |`,
    )
  }
  lines.push('')
}
writeFileSync(output, lines.join('\n') + '\n')
console.log(JSON.stringify({ total: Object.values(totals).reduce((a, b) => a + b, 0), ...totals }))
